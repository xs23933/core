// Enum 定义单个枚举类型配置。
type Enum struct {
	Name      string   // 类型名称，例如 "UserStatus"
	Values    []string // 枚举值，例如 ["none", "active", "disabled"]
	Sensitive bool     // 为 true 时，UnmarshalJSON 区分大小写
}

// EnumConfig 是枚举生成的顶层配置。
type EnumConfig struct {
	Package string // 目标包名，例如 "constants"
	Output  string // 输出目录，默认为 "."
	Enums   []Enum // 待生成的枚举列表
}

