package gen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/build"
	"go/parser"
	"go/token"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

const generatedHeader = "// Code generated by core. DO NOT EDIT.\n"

// GenerateEnumsInDir scans one module tree. Check mode never writes files.
// All configs and output conflicts are checked before the first write.
func GenerateEnumsInDir(root string, check bool) error {
	root, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	info, err := os.Lstat(root)
	if err != nil {
		return err
	}
	if !info.IsDir() {
		return fmt.Errorf("scan root must be a directory: %s", root)
	}
	groups := make(map[string][]string)
	err = filepath.WalkDir(root, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			if path != root {
				switch entry.Name() {
				case ".git", "vendor", "node_modules":
					return filepath.SkipDir
				}
				if _, err := os.Lstat(filepath.Join(path, "go.mod")); err == nil {
					return filepath.SkipDir
				} else if !os.IsNotExist(err) {
					return err
				}
			}
			return nil
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return nil
		}
		if entry.Name() == "enums.yaml" || strings.HasSuffix(entry.Name(), "_enums.yaml") {
			if !entry.Type().IsRegular() {
				return fmt.Errorf("config is not a regular file: %s", path)
			}
			groups[filepath.Dir(path)] = append(groups[filepath.Dir(path)], path)
		}
		return nil
	})
	if err != nil {
		return err
	}
	outputs := make(map[string][]byte)
	owners := make(map[string]string)
	for _, dir := range sortedKeys(groups) {
		combined := EnumConfig{}
		local := make(map[string][]byte)
		for _, path := range groups[dir] {
			data, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			var cfg EnumConfig
			decoder := yaml.NewDecoder(bytes.NewReader(data))
			decoder.KnownFields(true)
			if err := decoder.Decode(&cfg); err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
			var extra any
			if err := decoder.Decode(&extra); err != io.EOF {
				return fmt.Errorf("%s: expected one YAML document", path)
			}
			if cfg.Package == "" || cfg.Output != "" {
				return fmt.Errorf("%s: package is required; output must be omitted for directory generation", path)
			}
			if combined.Package != "" && combined.Package != cfg.Package {
				return fmt.Errorf("%s: conflicting package %s", path, cfg.Package)
			}
			combined.Package = cfg.Package
			combined.Enums = append(combined.Enums, cfg.Enums...)
			files, err := RenderEnums(cfg)
			if err != nil {
				return fmt.Errorf("%s: %w", path, err)
			}
			source := filepath.Base(path)
			for name, code := range files {
				target := filepath.Join(dir, name)
				if previous, ok := owners[target]; ok {
					return fmt.Errorf("%s and %s both generate %s", previous, source, target)
				}
				owners[target] = source
				code = bytes.Replace(code, []byte(generatedHeader), []byte(generatedHeader+"// Source: "+strconv.Quote(source)+"\n"), 1)
				outputs[target], local[name] = code, code
			}
		}
		if _, err := RenderEnums(combined); err != nil {
			return fmt.Errorf("%s: %w", dir, err)
		}
		if err := checkPackage(dir, combined.Package, local); err != nil {
			return err
		}
	}
	for _, path := range sortedKeys(outputs) {
		if err := checkGeneratedTarget(path, owners[path]); err != nil {
			return err
		}
	}
	var changed []string
	for _, path := range sortedKeys(outputs) {
		existing, err := os.ReadFile(path)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if !bytes.Equal(existing, outputs[path]) {
			changed = append(changed, path)
		}
	}
	if check && len(changed) > 0 {
		return fmt.Errorf("enum outputs missing or out of date:\n%s", strings.Join(changed, "\n"))
	}
	if !check {
		for _, path := range changed {
			if err := writeGenerated(path, outputs[path]); err != nil {
				return err
			}
		}
	}
	return nil
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func checkGeneratedTarget(path, source string) error {
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if !info.Mode().IsRegular() {
		return fmt.Errorf("refusing non-regular output %s", path)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	prefix := generatedHeader
	if source != "" {
		prefix += "// Source: " + strconv.Quote(source) + "\n"
	}
	if !bytes.HasPrefix(data, []byte(prefix)) {
		return fmt.Errorf("refusing to overwrite unowned file %s", path)
	}
	return nil
}

func writeGenerated(path string, code []byte) error {
	old, err := os.ReadFile(path)
	if err == nil && bytes.Equal(old, code) {
		return nil
	}
	if err != nil && !os.IsNotExist(err) {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(path), ".core-enum-*")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	if _, err := file.Write(code); err != nil {
		file.Close()
		return err
	}
	if err := file.Chmod(0o644); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}

func declarations(file *ast.File) []string {
	var names []string
	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil {
				if d.Name.Name != "init" {
					names = append(names, d.Name.Name)
				}
			} else if len(d.Recv.List) > 0 {
				receiver := d.Recv.List[0].Type
				if pointer, ok := receiver.(*ast.StarExpr); ok {
					receiver = pointer.X
				}
				if ident, ok := receiver.(*ast.Ident); ok {
					names = append(names, ident.Name+"."+d.Name.Name)
				}
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					names = append(names, s.Name.Name)
				case *ast.ValueSpec:
					for _, name := range s.Names {
						if name.Name != "_" {
							names = append(names, name.Name)
						}
					}
				}
			}
		}
	}
	return names
}

func checkPackage(dir, pkg string, outputs map[string][]byte) error {
	names := make(map[string]string)
	record := func(name string, code []byte, generated bool) error {
		file, err := parser.ParseFile(token.NewFileSet(), name, code, 0)
		if err != nil {
			return err
		}
		if file.Name.Name != pkg {
			return fmt.Errorf("%s: package %s conflicts with %s", name, file.Name.Name, pkg)
		}
		for _, symbol := range declarations(file) {
			if previous, exists := names[symbol]; exists {
				return fmt.Errorf("%s: identifier %s already declared in %s", name, symbol, previous)
			}
			if generated {
				names[symbol] = name
			}
		}
		return nil
	}
	for _, name := range sortedKeys(outputs) {
		if err := record(name, outputs[name], true); err != nil {
			return err
		}
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") || strings.HasSuffix(entry.Name(), "_test.go") {
			continue
		}
		if _, expected := outputs[entry.Name()]; expected {
			continue
		}
		matches, err := build.Default.MatchFile(dir, entry.Name())
		if err != nil {
			return err
		}
		if !matches {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, entry.Name()))
		if err != nil {
			return err
		}
		if bytes.HasPrefix(data, []byte(generatedHeader+"// Source: ")) {
			return fmt.Errorf("stale enum output %s; review and remove it explicitly", filepath.Join(dir, entry.Name()))
		}
		if err := record(entry.Name(), data, false); err != nil {
			return err
		}
	}
	return nil
}
